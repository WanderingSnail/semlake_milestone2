"""Write every number the paper prints, from the files in benchmarks/results/.

The paper (paper/semlake_pvldb.tex) reads ``paper/generated/numbers.tex`` for
the numbers in its text and ``paper/generated/tab_*.tex`` for its tables. Rerun
this script after rerunning any experiment; nothing in the paper is typed in.

    python benchmarks/paper_numbers.py
"""

from __future__ import annotations

import csv
import json
import os
import platform
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

RESULTS = ROOT / "benchmarks" / "results"
OUT = ROOT / "paper" / "generated"

SYSTEM_LABELS = {
    "b1": "B1 file OCC", "b1r": "B1R Delta-style", "b2": "B2 copy-on-write", "b3": "B3 tuple versioning",
    "b4": "B4 CRDT", "dolt": "B5 Dolt", "b6": "B6 SSI", "semlake_static": "\\sys, static test only",
    "semlake": "\\sys", "semlake_group": "\\sys, group commit",
}


def _json(name: str) -> dict:
    return json.loads((RESULTS / name).read_text(encoding="utf-8"))


def _csv(name: str) -> list[dict]:
    with (RESULTS / name).open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _f(value: float | None, digits: int = 2) -> str:
    return "--" if value is None else f"{value:.{digits}f}"


def _ms(seconds: float) -> str:
    ms = seconds * 1e3
    return f"{ms:.2f}" if ms < 10 else f"{ms:.1f}"


def _count(n: float) -> str:
    return f"{int(round(n)):,}".replace(",", "{,}")


def _score(rows: list[dict], system: str) -> dict:
    tp = fp = fn = tn = aborts = 0
    for row in rows:
        value = row.get(system, "")
        if value == "":
            continue
        expect = int(row["expect"]) == 1
        flagged = value == "1"
        aborts += value == "2"
        tp += flagged and expect
        fp += flagged and not expect
        fn += (not flagged) and expect
        tn += (not flagged) and not expect
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn, "aborts": aborts,
            "precision": tp / (tp + fp) if tp + fp else None, "recall": tp / (tp + fn) if tp + fn else None}


class Numbers:
    def __init__(self) -> None:
        self.macros: dict[str, str] = {}

    def __setitem__(self, name: str, value) -> None:
        self.macros[name] = str(value)

    def write(self) -> None:
        lines = ["% Generated by benchmarks/paper_numbers.py from benchmarks/results/. Do not edit."]
        lines += [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in sorted(self.macros.items())]
        missing = self.missing()
        if missing:
            print(f"no result yet for: {', '.join(missing)}")
            lines.append("% Numbers whose results file is missing print as ??.")
            lines += [f"\\providecommand{{\\{name}}}{{\\textbf{{??}}}}" for name in missing]
        (OUT / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    def missing(self) -> list[str]:
        import re

        text = (ROOT / "paper" / "semlake_pvldb.tex").read_text(encoding="utf-8")
        used = set(re.findall(r"\\([A-Z][A-Za-z]+)", text))
        latex = {"Comment", "Delta", "ElsIf", "Else", "EndFor", "EndIf", "For", "If", "Phi", "Pi", "Return", "State"}
        return sorted(used - latex - set(self.macros))


def correctness(n: Numbers) -> None:
    suite = _csv("m1s_cases.csv")
    pairs = _json("tpch_pairs.json")
    order = ("b1", "b1r", "b2", "b3", "b4", "dolt", "b6", "semlake_static", "semlake")
    s = {name: _score(suite, name) for name in order}
    t = pairs["summary"]
    n["SuiteCases"] = len(suite)
    n["SuitePos"] = sum(int(r["expect"]) for r in suite)
    for key, name in (("Sem", "semlake"), ("BoneR", "b1r"), ("Dolt", "dolt"), ("Bsix", "b6"), ("Static", "semlake_static")):
        n[f"{key}SuiteRec"] = _f(s[name]["recall"])
        n[f"{key}SuitePrec"] = _f(s[name]["precision"])
        n[f"{key}SuiteFP"] = s[name]["fp"]
        n[f"{key}SuiteTP"] = s[name]["tp"]
        n[f"{key}TpchRec"] = _f(t[name]["recall"])
        n[f"{key}TpchPrec"] = _f(t[name]["precision"])
        n[f"{key}TpchFP"] = t[name]["fp"]
    n["TpchPairs"] = len(pairs["cases"])
    n["TpchPos"] = t["semlake"]["tp"] + t["semlake"]["fn"]
    n["TpchRows"] = _count(pairs["rows"])
    n["TpchSF"] = pairs["scale_factor"]
    n["TpchFiles"] = -(-pairs["rows"] // pairs["rows_per_file"])

    lines = [
        "\\begin{table}[t]", "\\centering", "\\footnotesize",
        "\\caption{Conflict detection on (a) the labelled scenarios and (b) the TPC-H refresh-versus-report pairs. "
        "TP and FP count reported semantic conflicts; Ab.\\ counts write-conflict aborts, which block a merge "
        "without naming a semantic reason.}",
        "\\label{tab:correctness}", "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}l rrrrr rrrr@{}}", "\\toprule",
        f"& \\multicolumn{{5}}{{c}}{{(a) {len(suite)} scenarios, {n.macros['SuitePos']} conflicts}} "
        f"& \\multicolumn{{4}}{{c}}{{(b) {len(pairs['cases'])} TPC-H pairs, {n.macros['TpchPos']} conflicts}} \\\\",
        "\\cmidrule(lr){2-6} \\cmidrule(l){7-10}",
        "Rule & TP & FP & Ab. & Rec. & Prec. & TP & FP & Rec. & Prec. \\\\", "\\midrule",
    ]
    for name in order:
        a, b = s[name], t[name]
        label = SYSTEM_LABELS[name]
        if name == "semlake":
            label = "\\textbf{\\sys}"
            lines.append("\\midrule")
        lines.append(f"{label} & {a['tp']} & {a['fp']} & {a['aborts']} & {_f(a['recall'])} & {_f(a['precision'])} "
                     f"& {b['tp']} & {b['fp']} & {_f(b['recall'])} & {_f(b['precision'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "tab_correctness.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def selectivity(n: Numbers) -> None:
    doc = _json("selectivity.json")
    pts = doc["points"]
    n["SelTrials"] = pts[0]["trials"]
    n["SelQsixFiles"] = doc["q6_files"]
    n["SelMinPct"] = f"{min(p['mean_fraction'] for p in pts) * 100:.2g}"
    n["SelMaxPct"] = f"{max(p['mean_fraction'] for p in pts) * 100:.2g}"
    at = min(pts, key=lambda p: abs(p["target_fraction"] - 0.001))
    n["BoneRSelAtOne"] = _f(at["b1r_false_block_rate"])
    n["StaticSelMean"] = _f(sum(p["semlake_static_false_block_rate"] for p in pts) / len(pts))
    n["SemSelMax"] = _f(max(p["semlake_false_block_rate"] for p in pts))


def scenarios(n: Numbers) -> None:
    rows = _csv("benchmark_run_summary.csv")

    def pick(workload: str, system: str, depth=None, contention=None) -> dict:
        for row in rows:
            if row["workload"] != workload or row["system"] != system:
                continue
            if depth is not None and int(float(row["manifest_depth"])) != depth:
                continue
            if contention is not None and abs(float(row["contention"]) - contention) > 1e-9:
                continue
            return row
        raise KeyError((workload, system, depth, contention))

    n["WtwoSemZero"] = _ms(float(pick("W2L", "semlake", contention=0.0)["merge_cpu_s"]))
    n["WtwoSemTwenty"] = _ms(float(pick("W2L", "semlake", contention=0.2)["merge_cpu_s"]))
    n["WtwoBoneZero"] = _ms(float(pick("W2L", "b1", contention=0.0)["merge_cpu_s"]))
    n["WtwoBoneTwenty"] = _ms(float(pick("W2L", "b1", contention=0.2)["merge_cpu_s"]))
    n["WtwoBfourZero"] = _ms(float(pick("W2L", "b4", contention=0.0)["merge_cpu_s"]))
    n["WtwoSemEst"] = _f(float(pick("W2L", "semlake", contention=0.0)["estimated_latency_s"]))
    n["WtwoBoneEst"] = _f(float(pick("W2L", "b1", contention=0.0)["estimated_latency_s"]))
    depths = sorted({int(float(r["manifest_depth"])) for r in rows if r["workload"] == "W4"})
    n["WfourSemOne"] = _ms(float(pick("W4", "semlake", depth=depths[0])["merge_cpu_s"]))
    n["WfourSemTen"] = _ms(float(pick("W4", "semlake", depth=depths[-1])["merge_cpu_s"]))
    n["WfourBoneTen"] = _ms(float(pick("W4", "b1", depth=depths[-1])["merge_cpu_s"]))
    n["WfourBtwoTen"] = _ms(float(pick("W4", "b2", depth=depths[-1])["merge_cpu_s"]))
    n["WfourBthreeTen"] = _ms(float(pick("W4", "b3", depth=depths[-1])["merge_cpu_s"]))
    n["WfourBthreeReq"] = _count(float(pick("W4", "b3", depth=depths[-1])["s3_requests"]))
    hist = sorted({int(float(r["manifest_depth"])) for r in rows if r["workload"] == "H1"})
    n["HistLow"], n["HistHigh"] = hist[0], hist[-1]
    lca = [float(pick("H1", "lca", depth=d)["merge_cpu_s"]) * 1e6 for d in (hist[0], hist[-1])]
    n["HistLca"] = f"{lca[0]:.1f} and {lca[1]:.1f}" if abs(lca[0] - lca[1]) >= 0.05 else f"{lca[0]:.1f}"
    n["HistSemLow"] = _ms(float(pick("H1", "semlake", depth=hist[0])["merge_cpu_s"]))
    n["HistSemHigh"] = _ms(float(pick("H1", "semlake", depth=hist[-1])["merge_cpu_s"]))
    w1s = max(int(float(r["manifest_depth"])) for r in rows if r["workload"] == "W1S")
    sem = pick("W1S", "semlake", depth=w1s)
    n["WoneSFilesK"] = w1s // 1000
    n["WoneSReqSem"] = _count(float(sem["s3_requests"]))
    n["WoneSPutSem"], n["WoneSGetSem"], n["WoneSListSem"] = sem["s3_put"], sem["s3_get"], sem["s3_list"]
    n["WoneSBytesSem"] = _count(float(sem["put_bytes"]))
    n["WoneSReqBone"] = _count(float(pick("W1S", "b1", depth=w1s)["s3_requests"]))
    b2 = pick("W1S", "b2", depth=w1s)
    n["WoneSReqBtwo"] = _count(float(b2["s3_requests"]))
    n["WoneSBtwoEst"] = _count(float(b2["estimated_latency_s"]))
    n["Repeats"] = max(int(r["trials"] or 1) for r in rows if r["workload"] == "W4")


def cost(n: Numbers) -> None:
    doc = _json("cost_efficiency.json")
    ten = next(p for p in doc["usd_per_1k"] if p["localized"]["reads_per_merge"] == 10)
    n["CostSemLoc"] = f"\\${ten['localized']['semlake_open_usd']:.3f}"
    n["CostSemUni"] = f"\\${ten['uniform']['semlake_open_usd']:.3f}"
    n["CostBtwo"] = f"\\${ten['localized']['b2_usd']:.3f}"
    n["CrossLoc"] = _count(doc["crossover_reads_per_merge"]["localized"])
    n["CrossUni"] = _count(doc["crossover_reads_per_merge"]["uniform"])


def scan(n: Numbers) -> None:
    doc = _json("tpch_scan.json")
    rows = doc["results"]
    loc = next(r for r in rows if r["layout"] == "localized")
    uni = next(r for r in rows if r["layout"] == "uniform" and abs(r["density"] - 0.01) < 1e-9)
    pct = lambda v: f"{v * 100:+.1f}".replace("-", "$-$")  # noqa: E731
    n["ScanLocOver"] = pct(loc["overhead_median"])
    n["ScanLocLow"] = pct(loc["overhead_ci_low"])
    n["ScanLocHigh"] = pct(loc["overhead_ci_high"])
    n["ScanUniOver"] = pct(uni["overhead_median"])
    n["ScanGroups"] = loc["groups"]
    n["ScanGroupRows"] = _count(doc["group_rows"])
    n["ScanRows"] = _count(doc.get("rows", loc["groups"] * doc["group_rows"]))
    lines = ["\\begin{table}[t]", "\\centering", "\\footnotesize",
             f"\\caption{{TPC-H Q6 on SF\\,1 \\texttt{{lineitem}} after a merge left deletes in a DV: median time "
             f"of {loc['processes']} processes, and overhead with a 95\\% confidence interval.}}",
             "\\label{tab:scan}", "\\setlength{\\tabcolsep}{3pt}",
             "\\begin{tabular}{@{}l r r r r l@{}}", "\\toprule",
             "Deletes & Rows & Clean groups & Base (ms) & DV (ms) & Overhead (95\\% CI) \\\\", "\\midrule"]
    for r in rows:
        lines.append(f"{r['layout']} & {r['density'] * 100:g}\\% & {r['clean_groups']}/{r['groups']} & "
                     f"{r['base_ms']:.1f} & {r['dv_ms']:.1f} & {pct(r['overhead_median'])}\\% "
                     f"({pct(r['overhead_ci_low'])} to {pct(r['overhead_ci_high'])}\\%) \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "tab_scan.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def compaction(n: Numbers) -> None:
    doc = _json("compaction.json")
    runs = doc["runs"]
    n["CompMerges"] = len(runs[0]["trace"])

    def run(layout, thr):
        return next(r for r in runs if r["layout"] == layout and r["threshold"] == thr)

    def pct(x):
        return f"{round(x * 100, 1) + 0.0:.1f}"

    n["CompLocNone"] = pct(run('localized', None)['mean_overhead'])
    n["CompUniNone"] = pct(run('uniform', None)['mean_overhead'])
    loc = min((r for r in runs if r["layout"] == "localized" and r["threshold"] is not None),
              key=lambda r: r["mean_overhead"])
    uni = min((r for r in runs if r["layout"] == "uniform" and r["threshold"] is not None),
              key=lambda r: r["mean_overhead"])
    n["CompLocThr"] = f"{loc['threshold'] * 100:g}\\%"
    n["CompLocBest"] = pct(loc['mean_overhead'])
    n["CompUniThr"] = f"{uni['threshold'] * 100:g}\\%"
    n["CompUniBest"] = pct(uni['mean_overhead'])
    n["CompUniRewrite"] = _count(uni["rows_rewritten_per_merge"])
    n["CompLocRewrite"] = _count(loc["rows_rewritten_per_merge"])
    n["CompDeletePct"] = f"{doc['delete_per_merge'] * 100:g}"


def packing(n: Numbers) -> None:
    doc = _json("packing.json")
    n["PackRows"] = _count(doc["rows"])
    n["PackChanged"] = doc["rows_changed_per_branch"]
    n["PackMax"] = _count(max(p["rows_per_file"] for p in doc["points"]))
    n["PackBoneMax"] = _f(max(p["b1_false_abort_rate"] for p in doc["points"]))


def swarm(n: Numbers) -> None:
    doc = _json("scion_sim_summary.json")
    rows = [r for r in doc["rows"] if r["mix"] == "agentic" and r["hot_rho"] == 0.0]
    agents = sorted({r["agents"] for r in rows})

    def get(a, system):
        return next(r for r in rows if r["agents"] == a and r["system"] == system)

    n["SwarmSeeds"] = len(doc["seeds"])
    n["SwarmHorizon"] = f"{doc['horizon_s']:g}"
    n["SwarmGroup"] = doc["group_size"]
    n["SwarmRtt"] = f"{doc['catalog_rtt_s'] * 1e3:g}"
    n["SwarmMaxAgents"] = agents[-1]
    from benchmarks import scion_sim

    n["SwarmFiles"] = scion_sim.N_FILES
    n["SwarmRowsPerFile"] = scion_sim.ROWS_PER_FILE
    n["SwarmWorkMean"] = f"{scion_sim.WORK_MEAN_S:g}"
    mix = scion_sim.MIXES["agentic"]
    n["SwarmDeletePct"] = f"{mix['delete'] * 100:g}"
    n["SwarmReportPct"] = f"{mix['report'] * 100:g}"
    n["SwarmUpdatePct"] = f"{(1 - mix['delete'] - mix['report']) * 100:g}"
    heavy = scion_sim.MIXES["purge-heavy"]
    n["SwarmHeavyDeletePct"] = f"{heavy['delete'] * 100:g}"
    n["SwarmHeavyReportPct"] = f"{heavy['report'] * 100:g}"
    n["SwarmHeavyAgents"] = " and ".join(str(a) for a in sorted({r["agents"] for r in doc["rows"]
                                                                  if r["mix"] == "purge-heavy"}))
    n["SwarmSemSixtyFour"] = f"{get(agents[-1], 'semlake')['commits_per_s']:.1f}"
    n["SwarmGroupSixtyFour"] = f"{get(agents[-1], 'semlake_group')['commits_per_s']:.1f}"
    mid = 32 if 32 in agents else agents[len(agents) // 2]
    n["SwarmBoneRFBThirtyTwo"] = f"{get(mid, 'b1r')['false_blocks']:.1f}"
    n["SwarmSemFBThirtyTwo"] = f"{get(mid, 'semlake')['false_blocks']:.1f}"
    total = lambda system: sum(r["hazards_committed_total"] for r in doc["rows"] if r["system"] == system)  # noqa: E731
    n["SwarmBoneHazTotal"] = total("b1")
    n["SwarmBtwoHazTotal"] = total("b2")
    n["SwarmBoneRHazTotal"] = total("b1r")
    n["SwarmSemHazTotal"] = total("semlake") + total("semlake_group")

    order = ("b1", "b1r", "b2", "semlake", "semlake_group")
    lines = ["\\begin{table}[t]", "\\centering", "\\footnotesize",
             f"\\caption{{Simulated swarm, {doc['horizon_s']:g}\\,s per run, mean of {len(doc['seeds'])} seeds "
             f"($\\pm$ 95\\% CI). Haz.: hazards committed and caught, summed over seeds. Blocks and redos: "
             f"false semantic blocks and false file-conflict redos per run.}}",
             "\\label{tab:swarm}", "\\setlength{\\tabcolsep}{2.5pt}",
             "\\begin{tabular}{@{}r l r r r r r@{}}", "\\toprule",
             "$N$ & Rule & Commits/s & Haz. & Caught & Blocks & Redos \\\\", "\\midrule"]
    shown = [a for a in (8, 32, agents[-1]) if a in agents]
    for i, a in enumerate(shown):
        if i:
            lines.append("\\midrule")
        for name in order:
            r = get(a, name)
            lines.append(f"{a} & {SYSTEM_LABELS[name]} & {r['commits_per_s']:.2f} $\\pm$ {r['commits_per_s_ci']:.2f} & "
                         f"{r['hazards_committed_total']} & {r['hazards_caught_total']} & {r['false_blocks']:.1f} & "
                         f"{r['redo_false']:.1f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "tab_swarm.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def environment(n: Numbers) -> None:
    import duckdb
    import pyarrow

    n["MachineCores"] = os.cpu_count()
    n["PythonVersion"] = platform.python_version()
    n["DuckdbVersion"] = duckdb.__version__
    n["PyarrowVersion"] = pyarrow.__version__

    def lines(folder: str) -> int:
        return sum(len(p.read_text(encoding="utf-8").splitlines()) for p in (ROOT / folder).glob("*.py"))

    n["EngineLines"] = _count(round(lines("semlake"), -2))
    n["BenchLines"] = _count(round(lines("benchmarks"), -2))
    from tests.test_fuzz import SEEDS

    n["FuzzSeeds"] = SEEDS


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    numbers = Numbers()
    for step in (environment, correctness, selectivity, scenarios, cost, scan, compaction, packing, swarm):
        try:
            step(numbers)
        except (FileNotFoundError, KeyError, StopIteration) as exc:
            print(f"{step.__name__}: missing input ({exc!r})")
    numbers.write()
    for table, label in (("tab_correctness", "correctness"), ("tab_scan", "scan"), ("tab_swarm", "swarm")):
        path = OUT / f"{table}.tex"
        if not path.exists():
            path.write_text(f"\\begin{{table}}[t]\\centering\\caption{{\\textbf{{??}} No result yet.}}"
                            f"\\label{{tab:{label}}}\\end{{table}}\n", encoding="utf-8")
    print(f"wrote {len(numbers.macros)} numbers to {OUT}")


if __name__ == "__main__":
    main()
